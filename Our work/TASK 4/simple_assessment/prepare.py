import ast
import difflib
from pathlib import Path
import sys
sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0,str(ROOT))
from task4_core.sources import sha
from task4_core.serialization import save

if __name__ == '__main__':
    audit = HERE/'audit'
    audit.mkdir(exist_ok=True)
    target = audit/'existing_task4_before.json'
    assert not target.exists(), 'Preserve previous baseline'
    paths = [p for p in ROOT.rglob('*') if p.is_file() and HERE not in p.parents]
    save(target,{str(p):sha(p) for p in paths})
    source = ROOT/'task4_core/runner.py'
    original = source.read_text(encoding='utf-8')
    text = original.replace('from .','from task4_core.')
    text = text.replace('class Task4Runner:', 'class SimpleRunner:')
    old = "        if len(world.instances) > 1000:\n            raise PermissionError('Formal execution gate CLOSED: pilot <=1000 instances only')"
    assert old in text
    text = text.replace(old,"        from experiment import authorize_world\n        authorize_world(world, policy)")
    text = text.replace("if policy not in ['Greedy','Spatial_MILP','AllL_Greedy']:",
                        "if policy not in ['Greedy','Spatial_MILP']:")
    text = text.replace("hashes.update(self.router.hashes)",
        "hashes.update(self.router.hashes)\n        hashes.update({str(p): sha(p) for p in sorted(Path(__file__).resolve().parent.glob('*.py'))})")
    text = text.replace("'formal_experiment':False", "'formal_experiment':True, 'study':'simple_assessment_v1_not_C1_C8'")
    header = '"""Local adapter of v3 runner, limited to user-authorized four simple scenarios.\nGenerated by prepare.py. Original v3 module and all models unchanged.\n"""\n'

    ast.parse(header+text)
    dest = HERE/'simple_runner.py'
    assert not dest.exists()
    dest.write_text(header+text,encoding='utf-8')
    (audit/'runner_adapter.diff').write_text(''.join(difflib.unified_diff(original.splitlines(True),
        (header+text).splitlines(True),fromfile=str(source),tofile=str(dest))),encoding='utf-8')
    save(audit/'runner_adapter_source.json',{'source':str(source),'sha256':sha(source),
        'adapter':str(dest),'sha256_adapter':sha(dest),'old_task4_files_preserved':len(paths),
        'changes':'absolute imports/class name; exact four-scenario gate; local code hashes; study metadata only'})
